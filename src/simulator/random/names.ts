export type PersonName = { firstName: string; lastName: string }

/** First name for `sex` (X picks from both lists) + two surnames, Spanish style. */
export function personName(rng: Rng, sex: Sex): PersonName {
  const pool =
    sex === 'F' ? FEMALE_NAMES : sex === 'M' ? MALE_NAMES : rng.pick([FEMALE_NAMES, MALE_NAMES])
  const first = rng.pick(SURNAMES)
  let second = rng.pick(SURNAMES)
  while (second === first) second = rng.pick(SURNAMES)
  return { firstName: rng.pick(pool), lastName: `${first} ${second}` }
}
